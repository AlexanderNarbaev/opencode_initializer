# ── Generate all multi-agent targets ─────────────────────────────────────────
# Usage: _generate_all_targets [project_dir]
_generate_all_targets() {
  local project_dir="${1:-$_PROJECT_DIR}"

  section "Multi-Agent Targets Generation"

  _generate_copilot_instructions "$project_dir"
  _generate_claude_settings "$project_dir"
  _generate_cursor_settings "$project_dir"
  _generate_vscode_settings "$project_dir"

  log "All multi-agent targets generated"
  info "  .github/copilot-instructions.md"
  info "  .claude/settings.json"
  info "  .cursor/settings.json"
  info "  .vscode/settings.json"
}

# ── Export functions ─────────────────────────────────────────────────────────
