#!/usr/bin/env bash
set -euo pipefail
# Module 53: Vertical Slices - HumanLayer Stage 4
# NOTE: sourced by setup.sh — set -euo pipefail is idempotent there (setup.sh already strict).
# Guard: only source when running standalone (avoid double-source under setup.sh)
# ── Idempotent module constants (safe under repeated sourcing) ──
MODULE_53_VERSION="${MODULE_53_VERSION:-"1.0.0"}"
MODULE_53_DIR="${MODULE_53_DIR:-"${OPENCODE_ROOT:-$PWD}/.opencode/vertical-slices"}"

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  source "${OPENCODE_ROOT:-$PWD}/src/lib/00-core.sh" || exit 1
  source "${OPENCODE_ROOT:-$PWD}/src/lib/00y-logging.sh" || exit 1
fi

generate_slice_template() {
    local name="${1:-}"; [[ -z "$name" ]] && { log_error "Name required"; return 1; }
    local slug=$(echo "$name" | tr '[:upper:]' '[:lower:]' | tr ' ' '-' | sed 's/[^a-z0-9-]//g')
    local ts=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    
    cat > "${MODULE_53_DIR}/${slug}.md" << EOF
# Vertical Slice: $name

**Created:** $ts | **Status:** DRAFT | **Author:** \${USER:-unknown}

## Slice Overview
**User Story:** [Link to US-XXX from product review]  
**End-to-End Flow:** [Description of complete user journey]

## Layers Implemented

### UI Layer
- Components: []
- Screens: []

### API Layer  
- Endpoints: []
- Request/Response schemas: []

### Business Logic
- Services: []
- Rules implemented: []

### Data Layer
- Entities: []
- Migrations: []

## Test Coverage
- [ ] Unit tests
- [ ] Integration tests
- [ ] E2E test

## Definition of Done
- [ ] Code complete
- [ ] Tests passing
- [ ] Documentation updated
- [ ] Security reviewed

*HumanLayer Stage 4 - Implement one vertical slice at a time*

## Traceability
- Spec: spec://feat/<feature-id>
- Product Review: [link]
- Architecture Decision: [link]
- Debt entries created: []

*Generated by Module 53 (Vertical Slices) — HumanLayer Stage 4*
EOF
}

list_slices() {
    [[ -d "$MODULE_53_DIR" ]] || { echo "No slices yet."; return 0; }
    ls -1 "$MODULE_53_DIR"/*.md 2>/dev/null | xargs -r -n1 basename
}

main_vertical_slices() {
    case "${1:-help}" in
        create) mkdir -p "$MODULE_53_DIR"; generate_slice_template "${2:-}" ;;
        list)   list_slices ;;
        *)      echo "Usage: opencode vertical-slices {create <name>|list}" ;;
    esac
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    main_vertical_slices "$@"
fi

